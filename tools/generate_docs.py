#!/usr/bin/env python3
"""Generate docs/COMMANDS.md from the manifests.

A hand-written command reference for 80 commands would be wrong within a week — the same
argument that makes the commands themselves generated. This reads the manifests, so the
reference and the CLI cannot disagree.

Usage::

    python3 tools/generate_docs.py            # write docs/COMMANDS.md
    python3 tools/generate_docs.py --check    # fail if it is out of date
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST_DIR = ROOT / "cli-manifest"
TARGET = ROOT / "docs" / "COMMANDS.md"

HEADER = """<!-- Generated by tools/generate_docs.py. Do not edit; change the manifests. -->

# Command reference

Every generated command, with the OSDU operation behind it. `osducs <noun> --help` shows the
same information at the terminal, and is the authority if the two ever disagree.

Commands are named for the **resource**, not the service that hosts it, so verbs live under
the thing they act on: searching records is `osducs record search`. See
[COMMAND-GRAMMAR.md](COMMAND-GRAMMAR.md) for why.

Hand-written commands — `osducs status`, `osducs record add`, `osducs file upload`,
`osducs file download`, `osducs completion` — are not listed here, since no manifest describes
their options; `record add` is in [USAGE.md](USAGE.md#writing-records), and the file commands in
[USAGE.md](USAGE.md#files). Neither are `group list`'s `--all` and `--type`, added by hand; see
[USAGE.md](USAGE.md#operations). Run `osducs --help` for the full tree.

Each command says what it **requires**: the roles its service's spec documents, which are also
what `--help` and a refused request show. They are what the spec says, not a guarantee; a
deployment may differ, and ADME answers some refusals with 401 rather than 403.

"""


def load() -> tuple[dict[str, list[dict]], list[tuple[str, str]]]:
    """Commands grouped by their top-level noun, and the hand-written ones with the roles they need.

    Each generated command carries the roles its operation's spec documents, from the same
    function that puts them in `--help` and in a refused request's message.
    """
    from generate_cli import documented_roles, resolve_spec

    grouped: dict[str, list[dict]] = {}
    handwritten: list[tuple[str, str]] = []
    for path in sorted(MANIFEST_DIR.glob("*.yaml")):
        manifest = yaml.safe_load(path.read_text(encoding="utf-8"))
        paths = yaml.safe_load(resolve_spec(manifest["spec"]).read_text(encoding="utf-8"))["paths"]

        def roles(op: dict) -> str | None:
            return documented_roles(paths[op["path"]][op["method"].lower()])

        for command in manifest.get("commands") or []:
            noun = command["command"].split()[0]
            grouped.setdefault(noun, []).append(
                {**command, "_service": manifest["service"], "_roles": roles(command["op"])})
        # `command` is optional on a hand-written entry, which may only account for an operation;
        # one without it has no row to give.
        for entry in manifest.get("handwritten") or []:
            if (name := entry.get("command")) and (required := entry.get("roles") or roles(entry["op"])):
                handwritten.append((name, required))
    return dict(sorted(grouped.items())), handwritten


def anchor(heading: str) -> str:
    """GitHub's anchor for a heading: lower case, punctuation dropped, spaces to hyphens."""
    return re.sub(r"[^\w\- ]", "", heading.strip().lower()).replace(" ", "-")


def options(command: dict) -> list[tuple[str, str, bool]]:
    """Every flag a command accepts, as (flags, help, required)."""
    found = []
    for config in (command.get("params") or {}).values():
        found.append((flags(config), (config.get("help") or "").strip(),
                      bool(config.get("required"))))
    body = command.get("body") or {}
    for config in (body.get("fields") or {}).values():
        found.append((flags(config), (config.get("help") or "").strip(),
                      bool(config.get("required"))))
    if body.get("flag") and not body.get("fields"):
        found.append((flags(body), (body.get("help") or "").strip(),
                      bool(body.get("required", True))))
    if paging := command.get("paging"):
        # Generated from `paging:` rather than declared, so it is described the same way here
        # as in --help, by the generator's own function.
        from generate_cli import all_option_help
        fields = body.get("fields") or {}
        excluded = [fields[name]["flag"] for name in [paging["limit"], *(paging.get("not-with") or [])]]
        found.append(("`--all`", all_option_help(paging["page-size"], paging["op"]["path"], excluded), False))
    if confirm := command.get("confirm"):
        from generate_cli import yes_option_help
        def flag(name):
            return (command.get("params") or {}).get(name, (body.get("fields") or {}).get(name, {})).get("flag")
        found.append(("`--yes`", yes_option_help(
            flag(confirm["when"]) if confirm.get("when") else None,
            flag(confirm["unless"]) if confirm.get("unless") else None), False))
    return found


def flags(config: dict) -> str:
    return ", ".join(f"`{f}`" for f in (config.get("short"), config.get("flag")) if f)


def rules(command: dict) -> list[str]:
    """Constraints the CLI enforces before sending anything."""
    stated = []
    if one_of := command.get("require-one-of"):
        stated.append("One of " + " or ".join(
            f"`{(command['params'][name]).get('flag')}`" for name in one_of) + " is required.")
    raw = command.get("mutually-exclusive") or []
    groups = raw if raw and isinstance(raw[0], list) else ([raw] if raw else [])
    lookup = {**(command.get("params") or {}), **((command.get("body") or {}).get("fields") or {})}
    for group in groups:
        stated.append(" and ".join(f"`{lookup[name].get('flag')}`" for name in group)
                      + " cannot be combined.")
    if confirm := command.get("confirm"):
        # What the question says, with each option it names shown as a slot to fill.
        message = re.sub(r"\{([^{}]*)\}", r"`<\1>`", " ".join(confirm["message"].split()))
        when = (f", when `{lookup[confirm['when']]['flag']}` is given" if confirm.get("when")
                else f", unless `{lookup[confirm['unless']]['flag']}` is given" if confirm.get("unless")
                else "")
        stated.append(f"Says what it is about to do and asks before going ahead{when}: "
                      f"*{message}* `--yes` skips the question.")
    return stated


def render() -> str:
    from generate_cli import needs_operator_role

    grouped, handwritten = load()
    out = [HEADER]

    out.append("| Noun | Commands |")
    out.append("|---|---|")
    for noun, commands in grouped.items():
        verbs = ", ".join(f"`{c['command'].split(maxsplit=1)[1]}`" for c in commands)
        out.append(f"| [`{noun}`](#{noun}) | {verbs} |")
    out.append("")

    # The question an operator asks first, answered in one place. Hand-written commands are
    # here too, since the rest of this page does not describe them.
    operator = sorted(
        [(c["command"], c["_roles"], True) for commands in grouped.values() for c in commands
         if needs_operator_role(c["_roles"])]
        + [(command, roles, False) for command, roles in handwritten if needs_operator_role(roles)])
    out.append("## Commands that need an operator role\n")
    out.append("Every role that admits these is an admin or ops role, such as `users.datalake.ops`, "
               "`users.datalake.admins` or a `service.*.admin`, which data users do not usually hold. "
               "Everything else a data user's viewer or editor groups admit, where the spec says.\n")
    out.append("| Command | Requires |")
    out.append("|---|---|")
    for command, roles, generated in operator:
        name = (f"[`osducs {command}`](#{anchor(f'osducs {command}')})" if generated
                else f"`osducs {command}` (hand-written)")
        out.append(f"| {name} | {roles} |")
    out.append("")

    for noun, commands in grouped.items():
        out.append(f"## {noun}\n")
        for command in sorted(commands, key=lambda c: c["command"]):
            out.append(f"### `osducs {command['command']}`\n")
            if summary := command.get("summary"):
                out.append(f"{summary}\n")
            operation = command["op"]
            out.append(f"`{operation['method'].upper()} {operation['path']}` "
                       f"— {command['_service']}\n")
            if command["_roles"]:
                out.append(f"Requires {command['_roles']}"
                           f"{' — an operator role' if needs_operator_role(command['_roles']) else ''}.\n")

            if flags_found := options(command):
                out.append("| Option | Required | Description |")
                out.append("|---|---|---|")
                for names, help_text, required in flags_found:
                    text = " ".join(help_text.split()) or "—"
                    out.append(f"| {names} | {'yes' if required else ''} | {text} |")
                out.append("")

            for rule in rules(command):
                out.append(f"> {rule}\n")

            examples = command.get("examples") or []
            if examples:
                out.append("```bash")
                for example in examples:
                    args = example["args"] if isinstance(example, dict) else example
                    out.append(f"osducs {command['command']} {str(args).strip()}")
                out.append("```\n")

    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if the file on disk is out of date")
    args = parser.parse_args()

    # The page carries the roles the specs document, so a fetched tree from another ref than
    # the pin would publish stale ones, which the CLI generator refuses to build from. Checked
    # the same way, overrides and sibling checkouts included.
    from generate_cli import stale_specs
    if stale := stale_specs():
        print(f"error: {stale}", file=sys.stderr)
        return 1

    produced = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != produced:
            print(f"{TARGET.relative_to(ROOT)} is out of date. "
                  f"Run python3 tools/generate_docs.py", file=sys.stderr)
            return 1
        print(f"{TARGET.relative_to(ROOT)} is up to date.")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(produced, encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(ROOT)} "
          f"({len(load()[0])} nouns, {sum(len(v) for v in load()[0].values())} commands)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
